// Shared types for hackathons. HackathonView is both what the UI renders and what the API
// stores in MongoDB (see server/src/models.ts), with tasks and team embedded.
// The server imports this file as types only, so keep it free of runtime code.

export type HackathonStatus = 'not_started' | 'in_progress' | 'submitted' | 'completed';
export type HackathonPriority = 'high' | 'medium' | 'low';
export type HackathonMode = 'online' | 'offline' | 'hybrid';
export type HackathonOutcome = 'pending' | 'participated' | 'shortlisted' | 'finalist' | 'winner';

/** Links a submission usually needs; empty string means not added yet */
export interface SubmissionLinks {
  repoUrl: string;
  demoVideoUrl: string;
  deckUrl: string;
  projectUrl: string;
}

export interface HackathonResult {
  outcome: HackathonOutcome;
  placement: string;
  prize: string;
  notes: string;
}

/** Emails sent to everyone on the team with an account, this many days before the submission deadline */
export interface ReminderSettings {
  enabled: boolean;
  daysBefore: number[];
}

export interface HackathonView {
  id: string;
  code: string;
  title: string;
  teamName: string;
  domain: string;
  psId: string;
  problemStatement: string;
  status: HackathonStatus;
  priority: HackathonPriority;
  completion: number;
  timeRemaining: string;
  kickoffDate: string;
  registrationDeadline: string | null;
  submissionDeadline: string | null;
  shortlistDate: string | null;
  finalPresentationDate: string | null;
  bannerImage: string;
  mode: HackathonMode | null;
  websiteLink: string | null;
  operatives: OperativeView[];
  tasks: TaskView[];
  submission: SubmissionLinks;
  result: HackathonResult;
  reminders: ReminderSettings;
  // Set by the server: whether the viewer owns the hackathon or was invited, and the edit version
  role?: 'owner' | 'member';
  version?: number;
}

/** A person on the team list. userId is set once they have accepted an invite and have an account */
export interface OperativeView {
  id: string;
  name: string;
  email: string;
  role: string;
  avatar: string;
  userId?: string | null;
  // Current username of a teammate who has joined (or a friend invited by account), filled in by the server
  username?: string | null;
  // A friend invited by account, before they accept
  invitedUserId?: string | null;
  // Invited by username before being friends: the invite waits until they accept the friend request
  awaitingFriend?: boolean;
  invitePending?: boolean;
  joinedAt?: string | null;
}

export interface TaskView {
  id: string;
  title: string;
  completed: boolean;
  weight: number;
  // Id of the operative the task is assigned to; the name is kept for display
  assigneeId?: string | null;
  assigneeName: string;
  assigneeAvatar: string;
  dueDate?: string | null;
}

export type NotificationKind = 'urgent' | 'team' | 'system';

/** Generated by the server from deadlines, tasks and team activity */
export interface AppNotification {
  id: string;
  kind: NotificationKind;
  title: string;
  description: string;
  time: string;
  unread: boolean;
  hackathonId: string | null;
  // Where the notification leads when it is not about one hackathon, e.g. "/friends"
  link?: string | null;
}

/** A task assigned to the signed-in user, with the hackathon it belongs to */
export interface MyTask extends TaskView {
  hackathonId: string;
  hackathonTitle: string;
  hackathonDeadline: string | null;
}

/** One hackathon as it appears on a profile: no problem statement, tasks or teammates' details */
export interface ProfileHackathon {
  id: string;
  title: string;
  teamName: string;
  domain: string;
  status: HackathonStatus;
  kickoffDate: string;
  submissionDeadline: string | null;
  finalPresentationDate: string | null;
  // The person's own role on the team list, e.g. "Frontend lead"
  role: string;
  position: 'Team lead' | 'Member';
  result: Pick<HackathonResult, 'outcome' | 'placement' | 'prize'>;
  projectUrl: string;
  // Only sent to the owner of the profile: whether it is left off the public page
  hidden?: boolean;
}

export interface PublicProfile {
  name: string;
  handle: string;
  bio: string;
  // Profile links by platform id, e.g. { github: "https://github.com/name" }
  links: Record<string, string>;
  memberSince: string;
  hackathons: ProfileHackathon[];
  projects: ProfileProject[];
}

/** The signed-in user's own profile settings, with every hackathon including hidden ones */
export interface ProfileSettings extends PublicProfile {
  handle: string;
  isPublic: boolean;
  canBePublic: boolean;
}

/** Someone shown in friend lists and search results */
export interface PersonSummary {
  userId: string;
  name: string;
  username: string;
  // Whether /u/<username> can be opened
  profilePublic: boolean;
}

export interface FriendRequest {
  id: string;
  person: PersonSummary;
  createdAt: string;
  // Teams and projects they also invited you to; the invitations arrive once you accept
  heldInvites?: string[];
}

export interface FriendsOverview {
  friends: (PersonSummary & { since: string })[];
  incoming: FriendRequest[];
  outgoing: FriendRequest[];
}

/** A team invite addressed to the signed-in user's account */
export interface TeamInvite {
  id: string;
  hackathonId: string;
  hackathonTitle: string;
  teamName: string;
  role: string;
  invitedBy: string;
  createdAt: string;
}

// --- Projects ---------------------------------------------------------------

export type ProjectStatus = 'idea' | 'building' | 'paused' | 'shipped' | 'archived';
export type BoardColumn = 'backlog' | 'todo' | 'in_progress' | 'review' | 'done';
export type TaskPriority = 'high' | 'medium' | 'low';

/** Links a project usually has; empty string means not added yet */
export interface ProjectLinks {
  repoUrl: string;
  demoUrl: string;
  videoUrl: string;
  deckUrl: string;
}

/** A card on the project board. assigneeId is a collaborator's account id */
export interface ProjectTask {
  id: string;
  title: string;
  notes: string;
  column: BoardColumn;
  priority: TaskPriority;
  assigneeId: string | null;
  dueDate: string | null;
  milestoneId: string | null;
  createdAt: string;
  // Set when the card reaches Done, cleared if it leaves Done
  completedAt: string | null;
  // Who assigned the card to its current assignee, and when
  assignedBy: string | null;
  assignedAt: string | null;
  // Pull request number in the project's GitHub repository; the card moves to Done when it is merged
  pullRequest?: number | null;
}

export interface Milestone {
  id: string;
  title: string;
  dueDate: string | null;
  done: boolean;
  doneAt: string | null;
}

export interface GitHubCommit {
  sha: string;
  message: string;
  author: string;
  date: string;
  url: string;
}

export interface GitHubPull {
  number: number;
  title: string;
  state: 'open' | 'closed' | 'merged';
  author: string;
  updatedAt: string;
  mergedAt: string | null;
  url: string;
}

/** What HackTrack last read from the project's public GitHub repository */
export interface ProjectGitHub {
  // "owner/name", taken from the project's code repository link
  repo: string;
  url: string;
  syncedAt: string | null;
  // Why the last sync failed, e.g. the repository is private or does not exist
  error: string | null;
  info: {
    description: string;
    defaultBranch: string;
    stars: number;
    forks: number;
    openIssues: number;
    language: string | null;
    pushedAt: string | null;
  } | null;
  commits: GitHubCommit[];
  pulls: GitHubPull[];
}

/** One line of the project's history, read as "<actorName> <text>" */
export interface ProjectActivity {
  id: string;
  at: string;
  actorId: string;
  actorName: string;
  text: string;
}

/** Someone invited to a project who has not accepted yet */
export interface ProjectInvitee {
  userId: string;
  name: string;
  username: string;
  invitedAt: string;
  // Not friends yet: the invitation reaches them once they accept the friend request
  waitingForFriendship: boolean;
}

/** A project invitation addressed to the signed-in user */
export interface ProjectInvite {
  projectId: string;
  projectTitle: string;
  tagline: string;
  invitedBy: string;
  invitedAt: string;
}

export interface ProjectMember {
  userId: string;
  name: string;
  username: string;
  position: 'owner' | 'collaborator';
  addedAt: string;
}

export interface ProjectHackathonLink {
  id: string;
  title: string;
  teamName: string;
  // Whether the viewer is on the hackathon's team and can open it
  canOpen: boolean;
}

export interface ProjectView {
  id: string;
  title: string;
  tagline: string;
  description: string;
  status: ProjectStatus;
  techStack: string[];
  links: ProjectLinks;
  startDate: string | null;
  targetDate: string | null;
  hackathon: ProjectHackathonLink | null;
  members: ProjectMember[];
  invited: ProjectInvitee[];
  tasks: ProjectTask[];
  milestones: Milestone[];
  // Newest first
  activity: ProjectActivity[];
  // Null when the code repository link is not a GitHub repository
  github: ProjectGitHub | null;
  progress: number;
  role: 'owner' | 'collaborator';
  createdAt: string;
  updatedAt: string;
}

/** A project as listed on the Projects page */
export interface ProjectSummary {
  id: string;
  title: string;
  tagline: string;
  status: ProjectStatus;
  techStack: string[];
  targetDate: string | null;
  hackathon: ProjectHackathonLink | null;
  members: Pick<ProjectMember, 'userId' | 'name' | 'username'>[];
  counts: { total: number; done: number; inProgress: number; overdue: number; mine: number };
  nextMilestone: Pick<Milestone, 'id' | 'title' | 'dueDate'> | null;
  progress: number;
  role: 'owner' | 'collaborator';
  updatedAt: string;
}

/** A project card assigned to the signed-in user, with the project it belongs to */
export interface MyProjectTask extends ProjectTask {
  projectId: string;
  projectTitle: string;
}

/** Someone who can be added to a project: a friend, or a teammate from the linked hackathon */
export interface ProjectCandidate extends PersonSummary {
  source: 'friend' | 'teammate';
}

/** A project as it appears on a profile */
export interface ProfileProject {
  id: string;
  title: string;
  tagline: string;
  status: ProjectStatus;
  techStack: string[];
  repoUrl: string;
  demoUrl: string;
  hackathonTitle: string | null;
  position: 'Owner' | 'Collaborator';
  progress: number;
  // Only sent to the owner of the profile: whether it is on the public page (projects are off by default)
  shown?: boolean;
}

export interface ToastMessage {
  id: string;
  type: 'success' | 'alert' | 'info' | 'warning';
  title: string;
  message: string;
}
